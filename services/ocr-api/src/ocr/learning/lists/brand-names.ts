/**
 * Brand names a hard page's best-guess drug name may be shown as, "Brand? (generic)" (drug-list.ts). A data table,
 * kept apart from the code so rows can be reviewed and added on their own (owner decision of 2026-11-05, about
 * 21:00 UTC, relayed by the coordinator: "add all those list now").
 *
 * Columns:
 * - brand: the brand name, lower case, as written on prescriptions.
 * - generic: what it stands for, as on NEML_GENERICS (drug-list.ts), or for a combination brand the listed generics
 *   it combines, joined by " + ", each of which is on the list.
 * - strength_forms: the strength and form of the listing that was checked (one example, not every strength sold).
 * - source: where the row comes from. A row is ACTIVE (used) only when its source cites a public NAFDAC listing:
 *   "NAFDAC Greenbook, NRN <registration number>, https://greenbook.nafdac.gov.ng/products/details/<id> (...)",
 *   a listing that was retrieved and checked (brand name and active ingredients) on the date given. Registration
 *   numbers are never recalled or invented. The 23 brands curated before this table (reviewed_by
 *   'coordinator-curated') stay active; where no Greenbook listing was found for one, its source is
 *   'coordinator-curated 2026-11'. Any other row without a NAFDAC source is left out of this file.
 * - reviewed_by: 'coordinator-curated' (the 23 brands curated with the coordinator before this table) or
 *   'pending-pharmacist' (added from the Greenbook on 2026-11-05; a pharmacist's review is pending, and does not gate
 *   use: every brand is shown with "?" and check_carefully on a hard page only).
 *
 * The listing status shown in the source (Active or Inactive on the Greenbook that day) is the registration's; an
 * inactive (lapsed) registration still names the brand and its ingredients, which is all this table uses.
 * A brand name alone does not fix what a product holds: the Greenbook also lists products under some of these
 * brand names with other active ingredients (such as "Panadol Extra", paracetamol and caffeine; "Lofnac Plus",
 * diclofenac and paracetamol; "Piriton Expectorant"; "Olfen 75 Injection", with lidocaine; "Ciprotab-TN", with
 * tinidazole). Such a name as written is not this brand (no exact match, and too far for a fuzzy one: tested in
 * drug-list.spec.ts), and a brand shown is always marked "?" for the clinician to check against the paper.
 */
export interface BrandRow {
  brand: string;
  generic: string;
  strength_forms: string;
  source: string;
  reviewed_by: 'coordinator-curated' | 'pending-pharmacist';
}

/** A NAFDAC Greenbook listing as a source: registration number (NRN) and the listing's address. */
export const NAFDAC_SOURCE = /^NAFDAC Greenbook, NRN [A-Z0-9]+-[0-9]+, https:\/\/greenbook\.nafdac\.gov\.ng\/products\/details\/\d+ \(.+\), retrieved \d{4}-\d{2}-\d{2}$/;
export const COORDINATOR_SOURCE = 'coordinator-curated 2026-11';

/** Whether a row is used: a NAFDAC-sourced row, or one of the coordinator-curated brands kept as they were. */
export function isActiveBrandRow(row: BrandRow): boolean {
  return NAFDAC_SOURCE.test(row.source) || (row.reviewed_by === 'coordinator-curated' && row.source === COORDINATOR_SOURCE);
}

